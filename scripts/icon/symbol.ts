/**
 * Quebra-Gelo app symbol: two equal rounded squares overlapping on the diagonal, outlines in
 * cream, the shared area filled with the accent (003 research R3/R4). Pure geometry, no I/O:
 * `scripts/generate-icons.ts` renders it, `scripts/__tests__/symbol.test.ts` checks it.
 *
 * Units: the square side is 1. Symbol space is centered on the symbol, so square A (top-left)
 * is centered at (-offset/2, -offset/2) and square B (bottom-right) at (+offset/2, +offset/2).
 * All shapes are defined on the outline centerline; the stroke is centered on it.
 */

export interface IconColors {
  background: string;
  outline: string;
  accent: string;
}

export interface IconSymbol {
  side: number;
  offset: number;
  radius: number;
  stroke: number;
  colors: IconColors;
}

export const SYMBOL: IconSymbol = {
  side: 1,
  offset: 0.42,
  radius: 0.24,
  stroke: 0.085,
  colors: { background: '#16131C', outline: '#F7F0E3', accent: '#FF6B4A' },
};

/** How the symbol is scaled into a square canvas. */
export type IconFit = { kind: 'bbox'; ratio: number } | { kind: 'radius'; ratio: number };

export interface IconLayout {
  /** Pixels per symbol unit. */
  scale: number;
  /** Symbol center in pixels. */
  cx: number;
  cy: number;
}

export interface Coverage {
  fill: number;
  outline: number;
}

/** Outer bounding-box side, stroke included. */
export const extent = (s: IconSymbol): number => s.side + s.offset + s.stroke;

/** Distance from the symbol center to its farthest painted point (outer edge of a corner arc). */
export const maxRadius = (s: IconSymbol): number =>
  Math.SQRT2 * (extent(s) / 2 - s.stroke / 2 - s.radius) + s.radius + s.stroke / 2;

export const layout = (s: IconSymbol, size: number, fit: IconFit): IconLayout => ({
  scale: fit.kind === 'bbox' ? (size * fit.ratio) / extent(s) : (size * fit.ratio) / maxRadius(s),
  cx: size / 2,
  cy: size / 2,
});

/** Signed distance from (px, py) to a rounded square centered at (cx, cy); negative inside. */
export const sdfRoundedRect = (px: number, py: number, cx: number, cy: number, half: number, r: number): number => {
  const qx = Math.abs(px - cx) - half + r;
  const qy = Math.abs(py - cy) - half + r;
  return Math.hypot(Math.max(qx, 0), Math.max(qy, 0)) + Math.min(Math.max(qx, qy), 0) - r;
};

const clamp01 = (v: number): number => Math.min(1, Math.max(0, v));

/**
 * Anti-aliased coverage of the fill (A ∩ B) and outline (stroke of A ∪ stroke of B) layers at a
 * pixel-space point. `aa` is the anti-aliasing width in pixels (1 = one pixel ramp).
 */
export const coverageAt = (x: number, y: number, l: IconLayout, s: IconSymbol, aa = 1): Coverage => {
  const u = (x - l.cx) / l.scale;
  const v = (y - l.cy) / l.scale;
  const half = s.side / 2;
  const o = s.offset / 2;
  const dA = sdfRoundedRect(u, v, -o, -o, half, s.radius);
  const dB = sdfRoundedRect(u, v, o, o, half, s.radius);
  const toPx = l.scale / aa;
  return {
    fill: clamp01(0.5 - Math.max(dA, dB) * toPx),
    outline: clamp01(0.5 - (Math.min(Math.abs(dA), Math.abs(dB)) - s.stroke / 2) * toPx),
  };
};

const n = (v: number): string => String(Math.round(v * 100) / 100);

/** Editable SVG master of the symbol on a `size`² canvas. */
export const toSvg = (s: IconSymbol, size: number, fit: IconFit, background: boolean): string => {
  const l = layout(s, size, fit);
  const side = s.side * l.scale;
  const rect = (sign: -1 | 1) => {
    const c = sign * (s.offset / 2) * l.scale;
    return `x="${n(l.cx + c - side / 2)}" y="${n(l.cy + c - side / 2)}" width="${n(side)}" height="${n(side)}" rx="${n(s.radius * l.scale)}"`;
  };
  const { background: bg, outline, accent } = s.colors;
  const stroke = `fill="none" stroke="${outline}" stroke-width="${n(s.stroke * l.scale)}"`;
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">`,
    '  <!-- Generated by scripts/generate-icons.ts from scripts/icon/symbol.ts. Edit the params there. -->',
    `  <defs><clipPath id="a"><rect ${rect(-1)}/></clipPath></defs>`,
    ...(background ? [`  <rect width="${size}" height="${size}" fill="${bg}"/>`] : []),
    `  <rect ${rect(1)} fill="${accent}" clip-path="url(#a)"/>`,
    `  <rect ${rect(-1)} ${stroke}/>`,
    `  <rect ${rect(1)} ${stroke}/>`,
    '</svg>',
    '',
  ].join('\n');
};
